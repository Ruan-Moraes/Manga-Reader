package com.toonlira.translationgateway.infrastructure.rendering;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.toonlira.translationgateway.domain.rendering.RenderPolicy;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

class PamRasterIoTest {
    private static final RenderPolicy POLICY = RenderPolicy.initial();

    @Test
    void roundTripsExactRgbaIncludingInvisibleRgbWithoutChangingSource() throws Exception {
        var image = new BufferedImage(3, 2, BufferedImage.TYPE_INT_ARGB);
        int[] pixels = {0x00123456, 0x7fabcdef, 0xff010203, 0x00000001, 0xfeff8000, 0xffffffff};
        image.setRGB(0, 0, 3, 2, pixels, 0, 3);
        var bytes = new ByteArrayOutputStream();
        PamRasterIo.write(image, bytes, POLICY);
        var decoded = PamRasterIo.read(new ByteArrayInputStream(bytes.toByteArray()), 3, 2, POLICY);
        assertThat(decoded.getRGB(0, 0, 3, 2, null, 0, 3)).containsExactly(pixels);
        assertThat(image.getRGB(0, 0, 3, 2, null, 0, 3)).containsExactly(pixels);
    }

    @Test
    void acceptsOfficialRgbPamWithCommentAndAddsOpaqueAlpha() throws Exception {
        var bytes = pam("P7\n# generated by dwebp\nWIDTH 1\nHEIGHT 1\nDEPTH 3\nMAXVAL 255\nTUPLTYPE RGB\nENDHDR\n",
            new byte[]{12, 34, 56});
        assertThat(PamRasterIo.read(new ByteArrayInputStream(bytes), 1, 1, POLICY).getRGB(0, 0))
            .isEqualTo(0xff0c2238);
    }

    @ParameterizedTest
    @MethodSource("invalidPam")
    void rejectsMalformedOrUnboundedInput(byte[] bytes) {
        assertThatThrownBy(() -> PamRasterIo.read(new ByteArrayInputStream(bytes), 1, 1, POLICY))
            .isInstanceOf(IOException.class).hasMessage("invalid-raster").hasNoCause();
    }

    @Test
    void rejectsPolicyDimensionsBeforeReadingPixelsOrAllocating() {
        var bytes = pam("P7\nWIDTH 12001\nHEIGHT 12001\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n", new byte[0]);
        assertThatThrownBy(() -> PamRasterIo.read(new ByteArrayInputStream(bytes), 12001, 12001, POLICY))
            .isInstanceOf(IOException.class).hasMessage("invalid-raster");
        var strict = new RenderPolicy("fixture", 100, 1, 1, 1, 100, 100, 12, 48, 2);
        assertThatThrownBy(() -> PamRasterIo.write(new BufferedImage(2, 1, BufferedImage.TYPE_INT_ARGB),
            new ByteArrayOutputStream(), strict)).isInstanceOf(IOException.class);
    }

    @Test
    void supportsPolicyBoundaryAndSubimagesWithoutAssumingRasterStride() throws Exception {
        var parent = new BufferedImage(5, 4, BufferedImage.TYPE_INT_ARGB);
        parent.setRGB(2, 2, 0x00203040);
        var image = parent.getSubimage(1, 1, 2, 2);
        var strict = new RenderPolicy("fixture", 100, 2, 2, 4, 100, 100, 12, 48, 2);
        var bytes = new ByteArrayOutputStream();
        PamRasterIo.write(image, bytes, strict);
        var result = PamRasterIo.read(new ByteArrayInputStream(bytes.toByteArray()), 2, 2, strict);
        assertThat(result.getRGB(1, 1)).isEqualTo(0x00203040);
    }

    static Stream<byte[]> invalidPam() {
        String header = "P7\nWIDTH 1\nHEIGHT 1\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n";
        return Stream.of(pam(header, new byte[3]), pam(header, new byte[5]),
            pam(header.replace("WIDTH 1", "WIDTH 2"), new byte[8]),
            pam(header.replace("WIDTH 1", "WIDTH 1\nWIDTH 1"), new byte[4]),
            pam(header.replace("WIDTH 1", "WIDTH 0"), new byte[4]),
            pam(header.replace("WIDTH 1", "WIDTH 999999999999999999"), new byte[4]),
            pam(header.replace("MAXVAL 255", "MAXVAL 65535"), new byte[4]),
            pam(header.replace("DEPTH 4", "DEPTH 5"), new byte[4]),
            pam(header.replace("RGB_ALPHA", "RGB"), new byte[4]),
            pam(header.replace("HEIGHT 1\n", ""), new byte[4]),
            pam(header.replace("ENDHDR", "EXTRA data\nENDHDR"), new byte[4]),
            pam(header.replace("P7", "P6"), new byte[4]),
            pam("P7\n#" + "x".repeat(1024) + "\n" + header.substring(3), new byte[4]),
            pam(header.replace("WIDTH 1", "WIDTH -1"), new byte[4]),
            pam(header.replace("ENDHDR\n", "ENDHDR"), new byte[4]));
    }

    private static byte[] pam(String header, byte[] pixels) {
        var output = new ByteArrayOutputStream();
        output.writeBytes(header.getBytes(StandardCharsets.US_ASCII));
        output.writeBytes(pixels);
        return output.toByteArray();
    }
}
